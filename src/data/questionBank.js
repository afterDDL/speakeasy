function shuffle(items) {
  return [...items].sort(() => Math.random() - 0.5);
}

export function getPart1Questions(limit = 8) {
  return shuffle(questionBank.part1.categories.flatMap((category) => category.questions)).slice(0, limit);
}

export function getRandomPart2Topic() {
  const topics = questionBank.part2_3.categories.flatMap((category) => category.topic_cards);
  return topics[Math.floor(Math.random() * topics.length)];
}

export function getPart3Questions(topic, limit = 6) {
  if (topic?.follow_ups?.length) {
    return shuffle(topic.follow_ups).slice(0, limit);
  }
  const sameCategory = questionBank.part3_topics
    .filter((part3Topic) => part3Topic.category_id === topic?.category_id)
    .flatMap((part3Topic) => part3Topic.questions);
  const pool = sameCategory.length
    ? sameCategory
    : questionBank.part3_topics.flatMap((part3Topic) => part3Topic.questions);
  return shuffle(pool).slice(0, limit);
}
